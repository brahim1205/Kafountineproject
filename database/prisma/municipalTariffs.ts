export function buildRuntimeTariffMap() {
  const categories = MUNICIPAL_TARIFFS.map((entry) => entry.category);
  const servicesByCategory = Object.fromEntries(
    MUNICIPAL_TARIFFS.map(({ category, services }) => [
      category.id,
      services.map<TransactionService>((service) => ({
        id: buildServiceId(category.id, service.nom),
        nom: service.nom,
        tarif: service.tarif,
        unite: service.unite,
        calcul: service.calcul,
      })),
    ])
  ) as Record<string, TransactionService[]>;

  return { categories, servicesByCategory };
}
