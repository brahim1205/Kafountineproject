type TransactionCategory = { id: string; nom: string; icon?: string; color?: string; description?: string };
type TransactionService = { id: string; nom: string; tarif: number; unite: string; calcul?: string };

export type MunicipalTariffSeed = {
  category: TransactionCategory;
  services: Array<{
    nom: string;
    tarif: number;
    unite: string;
    calcul?: string;
  }>;
};

export function slugify(value: string) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function buildServiceId(categoryId: string, serviceName: string) {
  return `${categoryId}-${slugify(serviceName)}`;
}

